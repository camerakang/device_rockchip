"""从唯一类型注册表生成四语言常量、说明和黄金向量。

新增类别只修改 mobocom_realtime/device_types.json 并递增 revision；
生成文件不手工维护，--check 用于测试和打包前检查，不写入文件。
"""
from pathlib import Path
import argparse
import json
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
# 允许从任意工作目录运行；帧编码复用公共实现。
sys.path.insert(0, str(ROOT))
from mobocom_realtime.wire import ALL_NODES, VERSION, Frame, Kind, Command, encode


def load_registry(path=None):
    """在生成前检查登记表，避免冲突或保留区ID进入任一语言SDK。

    path供测试传入临时错误登记表；正常生成始终读取公共登记表。
    revision是SDK登记表修订，不是Control线版本，也不新增线上字段。
    """
    data = json.loads((path or ROOT / 'mobocom_realtime/device_types.json').read_text(encoding='utf-8'))
    if data['schema'] != 1 or not isinstance(data['revision'], int) or data['revision'] < 1:
        raise ValueError('invalid registry schema/revision')
    types = data['types']
    if not types:
        raise ValueError('empty device type registry')
    ids, symbols = set(), set()
    for entry in types:
        value = int(entry['id'], 16)
        # 范围表示用途；范围内空位也必须登记后才能使用，不能自行分配。
        expected = 'virtual' if 0x8000 <= value <= 0x8fff else 'production' if 0x9000 <= value <= 0xefff else None
        if entry['scope'] != expected or expected is None or not re.fullmatch(r'0x[0-9A-Fa-f]{4}', entry['id']):
            raise ValueError('invalid type ID/range: ' + entry['id'])
        if value in ids or entry['symbol'] in symbols:
            raise ValueError('duplicate device type ID/symbol')
        if not re.fullmatch(r'[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*', entry['symbol']) or not entry['name']:
            raise ValueError('invalid device type name')
        ids.add(value); symbols.add(entry['symbol'])
    return data


def camel(symbol):
    """登记表/Python用FOCUS_MOTOR，C++/TypeScript统一导出FocusMotor。"""
    return ''.join(part.title() for part in symbol.split('_'))


def render(data):
    """返回生成文件的UTF-8字节；排序和LF换行保证快照可复算。

    先构造全部结果，再由main写入；校验模式使用相同生成路径，
    同时发现常量、文档、测试向量与登记表之间的漂移。
    """
    types = sorted(data['types'], key=lambda t: int(t['id'], 16))
    notice = 'Generated by tools/generate_device_types.py; edit device_types.json, not this file.'
    # 把维护规则一同生成到SDK入口，复制SDK的开发者也能看到用途边界。
    cpp = [f'// {notice}', '// 自动生成：新增类型请修改公共注册表并重新生成，不直接修改此文件。',
           '#pragma once', '#include <cstdint>', 'namespace mobocom {',
           '// SDK注册表修订号；不作为Control帧字段发送。',
           f'inline constexpr std::uint32_t DeviceTypeRegistryRevision={data["revision"]};',
           '// 逻辑设备类别：不表示UID、网络地址、资源单位或硬件型号。', 'enum class DeviceType:std::uint16_t {']
    cpp += [f'    {camel(t["symbol"])}={t["id"]}, // {t["name"]}；{"仅软件测试，禁止声明为真实设备" if t["scope"] == "virtual" else "正式类别ID，实际能力另查类别契约与CAPS"}' for t in types]
    cpp += ['};', '// 保持DeviceProfile.type的u16存储与线格式，调用处无需写裸数值。',
            'constexpr std::uint16_t device_type_id(DeviceType type){return static_cast<std::uint16_t>(type); }']
    for name, entries in [('is_registered_device_type', types), ('is_virtual_device_type', [t for t in types if t['scope'] == 'virtual']), ('is_production_device_type', [t for t in types if t['scope'] == 'production'])]:
        cpp += ['// 只接受表内明确登记值；所属数值范围不能代替登记。' if name == 'is_registered_device_type' else
                '// 判断登记用途，不证明驱动、反馈或机械安全已经实现。']
        cpp += [f'constexpr bool {name}(std::uint16_t type){{switch(type){{']
        cpp += [f'    case device_type_id(DeviceType::{camel(t["symbol"])}):' for t in entries]
        cpp += ['        return true; default:return false;}}']
    cpp += ['}']

    py = [f'"""{notice}"""', '# 自动生成：新增类型请修改公共注册表并重新生成，不直接修改此文件。',
          'from enum import IntEnum', '# SDK注册表修订；不新增Control线上字段。', f'REGISTRY_REVISION = {data["revision"]}', '',
          'class DeviceType(IntEnum):', '    """逻辑设备类别；UID、网络地址、资源单位分别定义。"""']
    py += [f'    {t["symbol"]} = {t["id"]}  # {t["name"]}；{"仅软件测试" if t["scope"] == "virtual" else "正式类别，能力另查契约与CAPS"}' for t in types]
    py += ['', 'def is_registered_device_type(value):', '    # IntEnum可直接编码为整数；排除bool、浮点与字符串，避免隐式转换误认ID。',
           '    # 只查已登记成员；保留区及未登记空位不自动成为合法类型。',
           '    return isinstance(value, int) and not isinstance(value, bool) and value in DeviceType._value2member_map_']
    for name, scope in [('is_virtual_device_type', 'virtual'), ('is_production_device_type', 'production')]:
        values = ', '.join(f'DeviceType.{t["symbol"]}' for t in types if t['scope'] == scope)
        py += ['', f'def {name}(value):', '    # 用途分类不是硬件能力或安全验收结果。',
               f'    return is_registered_device_type(value) and value in ({values},)']

    ts = [f'// {notice}', '// 自动生成：新增类型请修改公共注册表并重新生成，不直接修改此文件。',
          '// SDK登记表修订，不改变Control线版本或字段。', f'export const DEVICE_TYPE_REGISTRY_REVISION={data["revision"]};',
          '// 逻辑设备类别；不能用类型ID推断资源单位、轴数或到位能力。', 'export enum DeviceType {']
    ts += [f'    {camel(t["symbol"])}={t["id"]}, // {t["name"]}；{"仅软件测试" if t["scope"] == "virtual" else "正式类别，能力另查契约与CAPS"}' for t in types]
    ts += ['}', '// 数值enum提供反向名称索引；只认登记成员，不按整个范围放行。',
           '// 返回true仅表示已登记，运动前仍须适配profile_version与CAPS；未知ID保留用于查询/停止。',
           'export function isRegisteredDeviceType(value:number):boolean{return Number.isInteger(value)&&typeof DeviceType[value]===\'string\';}']
    for name, scope in [('isVirtualDeviceType', 'virtual'), ('isProductionDeviceType', 'production')]:
        cases = ''.join(f'case DeviceType.{camel(t["symbol"])}:' for t in types if t['scope'] == scope)
        ts += ['// 判断登记用途，不证明设备驱动或安全参数已经实现。',
               f'export function {name}(value:number):boolean{{switch(value){{{cases}return true;default:return false;}}}}']

    rust = [f'// {notice}', '// Explicit registered IDs, never reserve or accept an entire range.',
            '#![allow(clippy::manual_range_patterns)]', f'pub const REGISTRY_REVISION: u32 = {data["revision"]};',
            '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', '#[repr(u16)]', 'pub enum DeviceType {']
    rust += [f'    {camel(t["symbol"])} = {t["id"]},' for t in types]
    rust += ['}']
    for name, entries in [('is_registered_device_type', types), ('is_virtual_device_type', [t for t in types if t['scope'] == 'virtual']), ('is_production_device_type', [t for t in types if t['scope'] == 'production'])]:
        rust += [f'pub fn {name}(value: u16) -> bool {{',
                 '    matches!(value, ' + ' | '.join(t['id'] for t in entries) + ')', '}']

    md = ['<!-- ' + notice + ' -->', '# 设备类型 ID 注册表', '', f'注册表修订：{data["revision"]}。数值唯一来源：[device_types.json](device_types.json)。', '',
          '| ID（十六进制） | 十进制 | SDK 标识 | 设备类别 | 用途 |', '| --- | --- | --- | --- | --- |']
    md += [f'| `{t["id"]}` | {int(t["id"],16)} | `{t["symbol"]}` | {t["name"]} | {"正式类型" if t["scope"] == "production" else "仅虚拟测试"} |' for t in types]
    md += ['', '## 使用规则', '',
           '- 正式类型范围 `0x9000～0xEFFF`，虚拟测试范围 `0x8000～0x8FFF`；范围内未登记值仍不可使用。其余值保留，`0x0000` 和 `0xFFFF` 不代表有效设备。没有厂商自行分配或临时私有类型范围。',
           '- 新增类型先修改唯一注册表、递增revision并生成/验证四语言SDK与向量；不得只在设备仓库、上位机或AI代码中写一个新数值。已发布ID不改含义、不复用，停用仍保留登记。',
           '- DISCOVER、HELLO/INFO、CAPS节点记录的type均为同一u16类别ID，小端传输；UID区分设备实例并用于寻址，profile_version区分类别契约版本，二者不替代type。',
           '- 类型指逻辑设备类别。跟焦接收器对外发布FOCUS_MOTOR，其下游电机用endpoint/resource区分；风机板发布FAN，多路风机不另造类型；云台独立节点发布GIMBAL。不是每个网络接口、下游UART/CAN/NRF24链路或每种板型号分配一个类型。',
           '- 同类别不同型号沿用type；资源、单位、轴数、来源、范围和动作需读取CAPS并核对profile_version及真实类别契约。改变已有契约字段含义需升级profile_version；不因型号不同自行申请新类型。确实改变逻辑类别时才登记新ID。',
           '- FAN保留已实现的0x9001。设备type与资源unit、动作opcode属于不同命名空间，即使数值相同也不能互相解释；本表不定义新设备的单位、动作或安全参数。',
           '- C++ DeviceCore的valid()和Python Profile.validate拒绝未登记类型。虚拟ID仅用于测试，测试驱动可以验证正式ID的编码，但不能据此声明实现了真实类别或启用硬件。',
           '- 旧主控遇到未识别type时保留原始数值，可发现、查询与STOP/ESTOP，显示“未知设备类型”；禁止自动套用其它类别运动控件。类型已登记也不等于主控已支持相应profile_version/能力，运动前仍需明确类别适配。',
           '- 跑步机、楼梯机、机械马、轨道车及跟焦/云台此处仅登记身份；真实资源与安全契约由对应设备工程填写，不虚构实际能力。', '', '## SDK入口', '',
           'C++：`#include "mobocom_device_types.hpp"`，用 `mobocom::device_type_id(mobocom::DeviceType::FocusMotor)` 填充DeviceProfile.type；mobocom_device.hpp也导出此头文件。', '',
           'TypeScript：从公共SDK导入 `DeviceType`、`isRegisteredDeviceType`、`isProductionDeviceType`、`isVirtualDeviceType`；例如 `DeviceType.FocusMotor`。', '',
           'Python：`from mobocom_realtime.device_types import DeviceType`；例如 `DeviceType.FOCUS_MOTOR`。', '',
           'Rust：`use mobocom_protocol::DeviceType;`，例如 `DeviceType::FocusMotor as u16`；crate 位于 [rust](rust/README.md)。', '',
           '运行 `python tools/generate_device_types.py` 生成常量、本文和类型编码向量；`--check` 只验证生成物与注册表一致。', '',
           '[device_type_vectors.json](device_type_vectors.json)覆盖全部登记ID的INFO、DISCOVER和CAPS；它们使用虚拟资源夹具，只验证身份字段，不能作为真实类别能力定义。']

    # 固定UID=2、boot=10、session=100，只变化设备类型字段。
    # INFO/CAPS为UID单播；DISCOVER为dst_uid=0的组播空payload，回复立即可取。
    uid = 2
    requests = [(Command.INFO, b'', uid), (Command.DISCOVER, b'', ALL_NODES), (Command.CAPS, struct.pack('<H', 0), uid)]
    cases = []
    for t in types:
        value = int(t['id'], 16)
        for command, payload, dst in requests:
            if command == Command.INFO: reply = struct.pack('<QHIQBHQ', uid, value, 1, 10, VERSION, 1, 1)
            elif command == Command.DISCOVER: reply = struct.pack('<HIQQI', value, 1, 10, 1, 1)
            else:
                # CAPS沿用虚拟跟焦的三资源/一动作夹具，仅检查type在节点记录中的编码。
                # 这些数值不是跑步机、机械马等正式类别的资源或安全配置。
                item = struct.pack('<HHBHIIIIIIIHHI', value, 1, 6, 100, 10000, 20000, 1000000, 50000, 3000000, 100000, 100000, 3, 1, 0)
                reply = struct.pack('<HHBH', 1, 5, 1, len(item)) + item
            cases.append({'symbol': t['symbol'], 'type': value, 'command': int(command),
                          'request': encode(Frame(Kind.REQUEST, 0, dst, 1, command, 100, payload)).hex(),
                          'reply': encode(Frame(Kind.RESPONSE, uid, ALL_NODES, 1, command, 100, reply)).hex()})
    vectors = {'virtual_fixture': True, 'registry_revision': data['revision'], 'scope': 'Type identity encoding only; not real hardware capabilities', 'cases': cases}
    hpp = ['// ' + notice, '// 仅验证类型身份编码：资源来自虚拟夹具，不定义真实硬件能力。',
           '#pragma once', '#include <cstdint>',
           '// request/reply各为一个完整UDP数据报（含CRC）的十六进制；回复在receive后立即可取。',
           'struct DeviceTypeVector {std::uint16_t type;const char* request;const char* reply;};', 'inline constexpr DeviceTypeVector device_type_vectors[]={']
    hpp += [f'    {{{c["type"]},"{c["request"]}","{c["reply"]}"}},' for c in cases]
    hpp += ['};']
    outputs = {'mobocom_realtime/cpp/mobocom_device_types.hpp': cpp, 'mobocom_realtime/device_types.py': py,
               'mobocom_realtime/typescript/device_types.ts': ts, 'mobocom_realtime/rust/src/device_types.rs': rust,
               'mobocom_realtime/DEVICE_TYPES.md': md,
               'mobocom_realtime/tests/device_type_vectors.hpp': hpp}
    result = {name: ('\n'.join(lines) + '\n').encode() for name, lines in outputs.items()}
    result['mobocom_realtime/device_type_vectors.json'] = (json.dumps(vectors, ensure_ascii=False, indent=2) + '\n').encode()
    return result


def main():
    # 打包和CI使用--check：不修补生成物，发现漂移即失败，交由维护者重新生成。
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    for name, content in render(load_registry()).items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise ValueError('generated device type file stale: ' + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(content)
    print('PASS device type registry generation' + (' check' if args.check else ''))


if __name__ == '__main__':
    main()
